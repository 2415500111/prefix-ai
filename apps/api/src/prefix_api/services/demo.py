"""Guest demo mode: one synthetic hospital that anyone can explore.

Everything in the demo hospital is made up: names, phone numbers and e-mail addresses are
generated, and no real patient data is ever loaded here. Messages are always logged to the
console, never sent (see ``ReminderSender``). The hospital's protocols are the four SAMPLE
protocols, approved for this organisation only.

The patient-level data is wiped and regenerated by ``populate_demo``, so the nightly reset
and the admin "Reset demo" button do the same thing. The organisation, its staff accounts
and its approved protocols are kept, so the approval history stays intact.
"""

