@dataclass(frozen=True, slots=True)
class DemoResult:
    organization_id: uuid.UUID
    patients: int
    appointments: int
    reminders_sent: int
    answers: int
    escalations: int


def demo_organization(session: Session) -> Organization | None:
    return session.scalar(select(Organization).where(Organization.is_demo.is_(True)))


def guest_user(session: Session, organization: Organization) -> User | None:
    return session.scalar(
        select(User).where(
            User.organization_id == organization.id,
            User.role == Role.DEMO_VIEWER,
            User.is_active.is_(True),
        )
    )


def ensure_demo_hospital(session: Session, *, admin_password: str) -> tuple[Organization, User]:
    """Create the demo hospital once: facilities, procedures, approved protocols and staff.

    Returns the organisation and its demo coordinator (used to create patients). The guest
    account is created here too; its password is random because guests never use one.
    """
    org = demo_organization(session)
    if org is None:
        org = Organization(
            name=DEMO_NAME,
            slug=DEMO_SLUG,
            country_code="IN",
            default_timezone="Asia/Kolkata",
            is_demo=True,
        )
        session.add(org)
        session.flush()

    if session.scalar(select(Facility).where(Facility.organization_id == org.id)) is None:
        session.add_all(
            Facility(
                organization_id=org.id,
                name=name,
                timezone="Asia/Kolkata",
                address=address,
                maps_url=f"https://maps.example.com/{uuid.uuid5(org.id, name)}",
                phone="+911100000000",
            )
            for name, address in _FACILITIES
        )

    codes = set(
        session.scalars(select(ProcedureType.code).where(ProcedureType.organization_id == org.id))
    )
    for code, name, minutes, cost, sedation in PROCEDURE_TYPES:
        if code not in codes:
            session.add(
                ProcedureType(
                    organization_id=org.id,
                    code=code,
                    name=name,
                    default_duration_minutes=minutes,
                    or_cost_per_minute=cost,
                    requires_sedation=sedation,
                )
            )
    session.flush()

    staff = {}
    for role, email, password in (
        (Role.ADMIN, f"admin@{DEMO_SLUG}.{DEMO_EMAIL_DOMAIN}", admin_password),
        (
            Role.COORDINATOR,
            f"coordinator@{DEMO_SLUG}.{DEMO_EMAIL_DOMAIN}",
            secrets.token_urlsafe(16),
        ),
        (Role.CLINICIAN, f"clinician@{DEMO_SLUG}.{DEMO_EMAIL_DOMAIN}", secrets.token_urlsafe(16)),
        (Role.DEMO_VIEWER, f"guest@{DEMO_SLUG}.{DEMO_EMAIL_DOMAIN}", secrets.token_urlsafe(16)),
    ):
        user = session.scalar(select(User).where(User.email == normalize_email(email)))
        if user is None:
            user = User(
                organization_id=org.id,
                email=normalize_email(email),
                full_name=f"Demo {role.value.title().replace('_', ' ')}",
                role=role,
                password_hash=hash_password(password),
            )
            session.add(user)
            session.flush()
        staff[role] = user

    if (
        session.scalar(select(PrepProtocol.id).where(PrepProtocol.organization_id == org.id))
        is None
    ):
        seed_sample_protocols(session, org)
        session.flush()
    clinician = StaffPrincipal(
        user_id=staff[Role.CLINICIAN].id, organization_id=org.id, role=Role.CLINICIAN
    )
    protocols = ProtocolService(session, get_embedding_provider("local"))
    drafts = session.scalars(
        select(PrepProtocol).where(
            PrepProtocol.organization_id == org.id, PrepProtocol.status == ProtocolStatus.DRAFT
        )
    ).all()
    for protocol in drafts:
        protocols.approve(
            clinician, protocol.id, acknowledge_sample=True, now=dt.datetime.now(dt.UTC)
        )
    session.flush()

    coordinator = staff[Role.COORDINATOR]
    return org, coordinator


def _shortest_prep(
    session: Session, org_id: uuid.UUID, procedures: list[ProcedureType]
) -> tuple[dt.timedelta, ProcedureType] | None:
    """The procedure whose prep needs the least notice, so its released slot can be backfilled."""
    best: tuple[dt.timedelta, ProcedureType] | None = None
    for procedure in procedures:
        approved = protocols_repo.list_approved_for_procedure(session, org_id, procedure.id)
        lead = prep_lead(session, approved[0].id) if approved else None
        if lead is not None and (best is None or lead < best[0]):
            best = (lead, procedure)
    return best


def _add_backfill_scenario(
    session: Session,
    coordinator: StaffPrincipal,
    facility: Facility,
    procedure: ProcedureType,
    lead: dt.timedelta,
    waiting: list[uuid.UUID],
    *,
    now: dt.datetime,
) -> None:
    """A released slot and patients waiting for the same procedure, to try a backfill."""
    released = PatientService(session).create(
        coordinator,
        PatientCreate(
            first_name="Released",
            last_name="Patient",
            date_of_birth=dt.date(1980, 1, 1),
            phone="+919990000099",
            email=f"released@{DEMO_EMAIL_DOMAIN}",
            preferred_language="en",
            preferred_channel=MessageChannel.SMS,
            consent_to_message=True,
        ),
        now=now,
    )
    session.flush()
    scheduled_at = now + lead + dt.timedelta(days=1)
    booked = AppointmentService(session).create(
        coordinator,
        AppointmentCreate(
            patient_id=released.id,
            facility_id=facility.id,
            procedure_type_id=procedure.id,
            scheduled_at=scheduled_at,
        ),
        now=now,
    )
    AppointmentService(session).cancel(
        coordinator,
        booked.id,
        AppointmentCancel(reason=CancellationReason.PATIENT_REQUESTED),
        now=now,
    )
    local_day = scheduled_at.astimezone(ZoneInfo(facility.timezone)).date()
    for index, patient_id in enumerate(waiting):
        WaitlistService(session).add(
            coordinator,
            WaitlistEntryCreate(
                patient_id=patient_id,
                procedure_type_id=procedure.id,
                earliest_date=local_day - dt.timedelta(days=1),
                latest_date=local_day + dt.timedelta(days=2),
                priority=1 if index == 0 else 0,
            ),
        )


def _wipe_patient_data(session: Session, org: Organization) -> None:
    """Remove patients, bookings and everything that hangs off them. Protocols stay."""
    session.execute(delete(Escalation).where(Escalation.organization_id == org.id))
    session.execute(delete(Task).where(Task.organization_id == org.id))
    session.execute(delete(Appointment).where(Appointment.organization_id == org.id))
    session.execute(delete(Patient).where(Patient.organization_id == org.id))
    session.flush()


def populate_demo(
    session_factory: sessionmaker[Session],
    *,
    now: dt.datetime,
    admin_password: str,
) -> DemoResult:
    """Make the demo hospital look busy: patients, bookings across the next week, reminders
    already sent, some answers, and a few escalations. Deterministic for a given ``now``'s day."""
    with session_factory() as session:
        org, coordinator_user = ensure_demo_hospital(session, admin_password=admin_password)
        _wipe_patient_data(session, org)
        org_id = org.id
        coordinator = StaffPrincipal(
            user_id=coordinator_user.id, organization_id=org_id, role=Role.COORDINATOR
        )
        facilities = list(
            session.scalars(select(Facility).where(Facility.organization_id == org_id))
        )
        procedures = list(
            session.scalars(select(ProcedureType).where(ProcedureType.organization_id == org_id))
        )
        rng = random.Random(_SEED)  # noqa: S311 - reproducible demo data, not a secret
        appointment_count = 0
        backfill = _shortest_prep(session, org_id, procedures)
        waiting: list[uuid.UUID] = []
        for index in range(PATIENT_COUNT):
            first = rng.choice(_FIRST_NAMES)
            last = rng.choice(_LAST_NAMES)
            patient = PatientService(session).create(
                coordinator,
                PatientCreate(
                    first_name=first,
                    last_name=last,
                    date_of_birth=dt.date(
                        1950 + rng.randrange(55), rng.randrange(1, 13), rng.randrange(1, 28)
                    ),
                    phone=f"+9199900{index + 1:05d}",
                    email=f"patient{index + 1}@{DEMO_EMAIL_DOMAIN}",
                    preferred_language="hi" if index % 4 == 0 else "en",
                    preferred_channel=MessageChannel.SMS,
                    consent_to_message=True,
                    on_anticoagulant=index % 5 == 0,
                    diabetic_on_insulin=index % 7 == 0,
                    on_glp1_agonist=index % 9 == 0,
                ),
                now=now,
            )
            session.flush()
            # Spread bookings from six hours to seven days ahead.
            offset = dt.timedelta(hours=6 + rng.randrange(0, 7 * 24 - 6))
            procedure = procedures[index % len(procedures)]
            AppointmentService(session).create(
                coordinator,
                AppointmentCreate(
                    patient_id=patient.id,
                    facility_id=facilities[index % len(facilities)].id,
                    procedure_type_id=procedure.id,
                    scheduled_at=now + offset,
                ),
                now=now,
            )
            appointment_count += 1
            if (
                backfill is not None
                and procedure.id != backfill[1].id
                and len(waiting) < WAITING_PATIENTS
            ):
                waiting.append(patient.id)
        if backfill is not None:
            lead, slot_procedure = backfill
            _add_backfill_scenario(
                session, coordinator, facilities[0], slot_procedure, lead, waiting, now=now
            )
        session.commit()

    reminders = dispatch_due_reminders(
        session_factory,
        ConsoleProvider(),
        PassthroughTranslator(),
        now=now,
        batch_size=1000,
    )
    answers = _answer_some_check_ins(session_factory, org_id, now)
    escalations = _add_sample_escalations(session_factory, org_id, now)
    logger.info("demo.populated", patients=PATIENT_COUNT, appointments=appointment_count)
    return DemoResult(
        organization_id=org_id,
        patients=PATIENT_COUNT,
        appointments=appointment_count,
        reminders_sent=reminders.get("sent", 0),
        answers=answers,
        escalations=escalations,
    )


def _answer_some_check_ins(
    session_factory: sessionmaker[Session], org_id: uuid.UUID, now: dt.datetime
) -> int:
    """Confirm about two in three open check-ins; a few "no" answers on critical steps raise
    escalations through the same code path as real replies."""
    answered = 0
    system = SystemPrincipal(organization_id=org_id, job="demo_seed")
    with session_factory() as session:
        check_ins = session.scalars(
            select(CheckIn)
            .where(CheckIn.organization_id == org_id, CheckIn.status == CheckInStatus.PENDING)
            .order_by(CheckIn.created_at)
        ).all()
        for index, check_in in enumerate(check_ins):
            event = session.get(PatientTimelineEvent, check_in.timeline_event_id)
            if event is None:
                continue
            step = session.get(PrepStep, event.step_id)
            patient = session.get(Patient, check_in.patient_id)
            appointment = session.get(Appointment, check_in.appointment_id)
            if step is None or patient is None or appointment is None:
                continue
            if index % 3 == 2:
                continue
            response = (
                CheckInResponse.NO if step.is_critical and index % 6 == 0 else CheckInResponse.YES
            )
            record_answer(
                session,
                principal=system,
                patient=patient,
                appointment=appointment,
                check_in=check_in,
                event=event,
                step=step,
                response=response,
                via="in the demo",
                purpose="demo_seed",
                now=now,
            )
            answered += 1
        session.commit()
    return answered


def _add_sample_escalations(
    session_factory: sessionmaker[Session], org_id: uuid.UUID, now: dt.datetime
) -> int:
    """A chest-pain report from a patient (urgent) and a question for a nurse (normal)."""
    samples = [
        (EscalationSeverity.URGENT, "Red-flag words: CHEST_PAIN\nPatient asked: I have chest pain"),
        (
            EscalationSeverity.NORMAL,
            "The approved steps do not answer the question\n"
            "Patient asked: Can I take my usual tablet?",
        ),
    ]
    system = SystemPrincipal(organization_id=org_id, job="demo_seed")
    with session_factory() as session:
        patients = session.scalars(
            select(Patient).where(Patient.organization_id == org_id).order_by(Patient.created_at)
        ).all()
        if not patients:
            return 0
        for offset, (severity, summary) in enumerate(samples):
            patient = patients[offset % len(patients)]
            appointment = session.scalar(
                select(Appointment).where(Appointment.patient_id == patient.id).limit(1)
            )
            if appointment is None:
                continue
            create_escalation(
                session,
                principal=system,
                patient=patient,
                appointment=appointment,
                severity=severity,
                summary=summary,
                purpose="demo_seed",
                source=EscalationSource.RED_FLAG
                if severity is EscalationSeverity.URGENT
                else EscalationSource.OUT_OF_PROTOCOL,
            )
        session.commit()
    return len(samples)


def new_admin_password() -> str:
    return secrets.token_urlsafe(12)


def guest_login(session: Session, settings: Settings, *, now: dt.datetime) -> TokenPair:
    org = demo_organization(session)
    guest = guest_user(session, org) if org is not None else None
    if org is None or guest is None:
        raise AuthenticationError("The guest demo is not set up yet. Run `make seed-demo`.")
    return AuthService(session, settings).guest_session(guest, now=now)


def reset_demo_for(
    principal: StaffPrincipal, session_factory: sessionmaker[Session], *, now: dt.datetime
) -> DemoResult:
    """Regenerate the demo's patient data. Only the demo hospital's own admin may do this."""
    principal.require(Permission.DEMO_RESET)
    with session_factory() as session:
        org = session.get(Organization, principal.organization_id)
        if org is None or not org.is_demo:
            raise PermissionDeniedError("Only the demo hospital's admin can reset the demo")
    return populate_demo(session_factory, now=now, admin_password=new_admin_password())


def demo_patient_link(
    session: Session, settings: Settings, *, language: str, now: dt.datetime
) -> tuple[str, str]:
    """A fresh single-use portal link for a demo patient who speaks ``language``.

    The link is issued as the demo guest, so the audit trail shows the demo account. Returns
    the link and the patient's (synthetic) name.
    """
    org = demo_organization(session)
    guest = guest_user(session, org) if org is not None else None
    if org is None or guest is None:
        raise NotFoundError("The demo hospital is not set up yet")
    patients = list(
        session.scalars(
            select(Patient).where(
                Patient.organization_id == org.id, Patient.preferred_language == language
            )
        )
    )
    if not patients:
        raise NotFoundError(f"No demo patient speaks '{language}'")
    patient = secrets.choice(patients)
    principal = StaffPrincipal(user_id=guest.id, organization_id=org.id, role=Role.DEMO_VIEWER)
    issued = PatientAccessService(session, settings).issue_magic_link(
        principal, patient.id, now=now
    )
    return issued.url, f"{patient.first_name} {patient.last_name}"
